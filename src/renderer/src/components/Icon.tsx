export type IconName = keyof typeof icons

export function Icon({
  name,
  size = 18,
  strokeWidth = 1.8,
  className
}: {
  name: string
  size?: number
  strokeWidth?: number
  className?: string
}) {
  const Component = icons[name] ?? Circle
  return <Component size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" />
}
